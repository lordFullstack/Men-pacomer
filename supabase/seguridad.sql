begin;

-- ── 1. Tabla de administradores ─────────────────────────────────────
-- Solo los usuarios listados aquí pueden modificar el menú. No basta con
-- "authenticated": si el registro público está activo, cualquiera podría crear cuenta.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;  -- sin políticas: invisible por la API
revoke all on public.admins from anon, authenticated;

create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = (select auth.uid()));
$$;
revoke all on function public.es_admin() from public;
grant execute on function public.es_admin() to anon, authenticated;

-- 👇 CAMBIA el correo por el del usuario que creaste en Authentication → Users
insert into public.admins (user_id)
select id from auth.users where email = 'CAMBIA_ESTO@correo.com'
on conflict do nothing;

-- ── 2. Columnas nuevas del negocio (WhatsApp y horario) ─────────────
alter table public.negocio
  add column if not exists whatsapp    text,
  add column if not exists hora_abre   text,   -- 'HH:MM', hora de Colombia
  add column if not exists hora_cierra text;

-- ── 3. ids autoincrementales en productos ───────────────────────────
-- Antes el navegador inventaba el id con Date.now()
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'productos' and column_name = 'id'
      and (is_identity = 'YES' or column_default is not null)
  ) then
    alter table public.productos alter column id add generated by default as identity;
  end if;
end $$;
select setval(pg_get_serial_sequence('public.productos', 'id'),
              (select coalesce(max(id), 0) + 1 from public.productos), false);

-- ── 4. RLS: todos leen, solo admins escriben ────────────────────────
alter table public.productos enable row level security;
alter table public.negocio   enable row level security;

-- Elimina las políticas anteriores de estas dos tablas (probablemente abiertas a anon)
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
           where schemaname = 'public' and tablename in ('productos', 'negocio')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

create policy "menu_lectura_publica" on public.productos for select to anon, authenticated using (true);
create policy "menu_admin_insert"    on public.productos for insert to authenticated with check (public.es_admin());
create policy "menu_admin_update"    on public.productos for update to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "menu_admin_delete"    on public.productos for delete to authenticated using (public.es_admin());

create policy "negocio_lectura_publica" on public.negocio for select to anon, authenticated using (true);
create policy "negocio_admin_insert"    on public.negocio for insert to authenticated with check (public.es_admin());
create policy "negocio_admin_update"    on public.negocio for update to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "negocio_admin_delete"    on public.negocio for delete to authenticated using (public.es_admin());

-- Defensa extra: anon ni siquiera tiene permiso de escritura a nivel de tabla
revoke insert, update, delete, truncate on public.productos, public.negocio from anon;
grant select on public.productos, public.negocio to anon, authenticated;
grant insert, update, delete on public.productos, public.negocio to authenticated;

-- ── 5. Storage: bucket productos-img ────────────────────────────────
-- Lectura pública sigue funcionando por ser bucket público (URL /object/public/...).
-- Elimina políticas existentes que mencionen este bucket y crea las de admin.
do $$
declare p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'storage' and tablename = 'objects'
             and (coalesce(qual, '') || coalesce(with_check, '')) like '%productos-img%'
  loop
    execute format('drop policy %I on storage.objects', p.policyname);
  end loop;
end $$;

-- Storage exige SELECT además de DELETE para poder borrar archivos
create policy "menu_img_admin_select" on storage.objects for select to authenticated
  using (bucket_id = 'productos-img' and public.es_admin());
create policy "menu_img_admin_insert" on storage.objects for insert to authenticated
  with check (bucket_id = 'productos-img' and public.es_admin());
create policy "menu_img_admin_update" on storage.objects for update to authenticated
  using (bucket_id = 'productos-img' and public.es_admin());
create policy "menu_img_admin_delete" on storage.objects for delete to authenticated
  using (bucket_id = 'productos-img' and public.es_admin());

commit;

